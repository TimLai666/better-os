//! Every word the window can show, in both shipped languages.
//!
//! The pattern matches Better Manager: one `Copy` struct, one constant per
//! locale, and a compile error the moment a string is added to one language
//! and forgotten in the other. Nothing here formats a number; that is
//! `monitor-views`' job, so both locales format identically.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Locale {
    System,
    EnUs,
    ZhTw,
}

impl Locale {
    pub(crate) fn resolved(self) -> Self {
        match self {
            Self::System => {
                let language = std::env::var("LANG")
                    .unwrap_or_default()
                    .to_ascii_lowercase();
                if language.contains("zh_tw")
                    || language.contains("zh-tw")
                    || language.contains("hant")
                {
                    Self::ZhTw
                } else {
                    Self::EnUs
                }
            }
            locale => locale,
        }
    }
}

