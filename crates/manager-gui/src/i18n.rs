pub(crate) fn copy(locale: Locale) -> &'static Copy {
    match locale.resolved() {
        Locale::ZhTw => &ZH_TW,
        Locale::EnUs | Locale::System => &EN,
    }
}

impl Locale {
    /// The kit's language for this choice, after `system` is resolved.
    pub(crate) fn words(self) -> better_ui::fluent::words::Locale {
        match self.resolved() {
            Locale::ZhTw => better_ui::fluent::words::Locale::TraditionalChinese,
            Locale::EnUs | Locale::System => better_ui::fluent::words::Locale::English,
        }
    }
}

