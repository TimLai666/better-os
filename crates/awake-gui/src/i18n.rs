//! Every word the window can show, in both shipped locales.
//!
//! The full window is allowed to say more than the tray menu does, so this
//! crate owns its own copy rather than borrowing the tray's `Labels`. The two
//! surfaces answer different questions: the menu has one line to say what is
//! happening, and this window has a whole section to explain it.
//!
//! `Copy` is a struct of `&'static str`, and each locale is one initializer of
//! that struct. A translation that is missing is a field that is missing, which
//! is a compile error. There is deliberately no map lookup and no English
//! fallback, because a fallback turns a missing translation into something only
//! a reader of that language would ever notice.

/// Which language the window is drawn in. `System` is resolved once per read so
/// switching to it at runtime takes effect immediately.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Locale {
    System,
    EnUs,
    ZhTw,
}

impl Locale {
    /// The concrete language `System` means on this machine.
    pub(crate) fn resolved(self) -> Self {
        match self {
            Self::System => {
                let language = std::env::var("LANG")
                    .unwrap_or_default()
                    .to_ascii_lowercase();
                if language.contains("zh_tw")
                    || language.contains("zh-tw")
                    || language.contains("hant")
                {
                    Self::ZhTw
                } else {
                    Self::EnUs
                }
            }
            locale => locale,
        }
    }

    pub(crate) fn as_key(self) -> &'static str {
        match self {
            Self::System => "system",
            Self::EnUs => "en-US",
            Self::ZhTw => "zh-TW",
        }
    }

    pub(crate) fn from_key(key: &str) -> Self {
        match key {
            "en-US" => Self::EnUs,
            "zh-TW" => Self::ZhTw,
            _ => Self::System,
        }
    }
}

