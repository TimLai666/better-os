#!/usr/bin/env bash
# Writes org.betteros.TouchpadScroll1.dbus-1.12.conf, the scroll pass-through's
# bus policy for Ubuntu 22.04 (ADR 0030). Its dbus-daemon 1.12 has no
# send_destination_prefix, and an allow that names an interface without a
# destination would let anyone send that interface to any name. So the policy
# names every instance's own bus name, event0 to event511, one rule each. A
# touchpad numbered past event511 on 22.04 gets an instance the window cannot
# reach, which the window shows as the pass-through being absent.
#
#   generate-bus-policy-1.12.sh           rewrite the file
#   generate-bus-policy-1.12.sh --check   fail when the file is not current
set -euo pipefail
HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
TARGET="$HERE/org.betteros.TouchpadScroll1.dbus-1.12.conf"
LAST_EVENT=511

generate() {
    cat <<'HEAD'
<?xml version="1.0"?>
<!DOCTYPE busconfig PUBLIC "-//freedesktop//DTD D-BUS Bus Configuration 1.0//EN"
 "http://www.freedesktop.org/standards/dbus/1.0/busconfig.dtd">
<!-- Better Touchpad scroll speed (ADR 0030), for Ubuntu 22.04. Generated by
     packaging/touchpad/generate-bus-policy-1.12.sh; do not edit. dbus-daemon
     1.12 has no send_destination_prefix, so every instance's name is listed.
     Only the service account may own a pass-through's name, and the service
     itself refuses a change from anyone but the person at the machine. -->
<busconfig>
  <policy user="_better-touchpad-scroll">
    <allow own_prefix="org.betteros.TouchpadScroll1"/>
  </policy>
  <policy context="default">
HEAD
    local event
    for ((event = 0; event <= LAST_EVENT; event++)); do
        printf '    <allow send_destination="org.betteros.TouchpadScroll1.event%d" send_interface="org.betteros.TouchpadScroll1"/>\n' "$event"
    done
    printf '  </policy>\n</busconfig>\n'
}

if [[ "${1:-}" == --check ]]; then
    if ! diff -q <(generate) "$TARGET" >/dev/null; then
        printf '%s is not what the generator writes; run it\n' "$TARGET" >&2
        exit 1
    fi
    exit 0
fi
generate > "$TARGET"
